def inline(t: str) -> str:
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<i>\1</i>", t)
    t = re.sub(r"`(.+?)`", r"<font face='Courier' size=8>\1</font>", t)
    return t


def P(t, st=B):
    return Paragraph(inline(t), st)


def bullets(items):
    return [Paragraph(inline(i), BUL, bulletText="•") for i in items]


def tbl(rows, widths, header=True, fs=7.8, align_right=()):
    data = [[Paragraph(inline(str(c)), ParagraphStyle("c", parent=B, fontSize=fs, leading=fs + 2.2, textColor=colors.white if header and i == 0 else colors.black,
                                                       alignment=2 if j in align_right and i > 0 else 0)) for j, c in enumerate(r)] for i, r in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    st = [("GRID", (0, 0), (-1, -1), .4, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
          ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8F7F1")])]
    if header:
        st.append(("BACKGROUND", (0, 0), (-1, 0), FOREST))
    t.setStyle(TableStyle(st))
    return t


def img(path: Path, width_mm: float, caption: str = ""):
    w, h = PILImage.open(path).size
    wd = width_mm * mm
    out = [Image(str(path), width=wd, height=wd * h / w)]
    if caption:
        out.append(Paragraph(inline(caption), CAP))
    return KeepTogether(out)


class Numbered(rl_canvas.Canvas):
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self._s = []

    def showPage(self):
        self._s.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        n = len(self._s)
        for i, st in enumerate(self._s):
            self.__dict__.update(st)
            if self._pageNumber > 1:
                self.setFont("Helvetica", 7.5)
                self.setFillColor(colors.HexColor("#66736C"))
                self.drawString(16 * mm, 9 * mm, f"{S['roll']} · Raj Tripathi · CaneSense AI: AI-Powered Precision Irrigation Intelligence for Sugarcane Farms")
                self.drawRightString(A4[0] - 16 * mm, 9 * mm, f"Page {self._pageNumber} of {n}")
            super().showPage()
        super().save()


def mark(c, x, y, s):
    c.setFillColor(FOREST); c.roundRect(x, y, s, s, s * .23, fill=1, stroke=0)
    c.setFillColor(LIME); c.circle(x + s / 2, y + s * .4, s * .22, fill=1, stroke=0)
    p = c.beginPath(); p.moveTo(x + s / 2, y + s * .84); p.lineTo(x + s * .3, y + s * .5); p.lineTo(x + s * .7, y + s * .5); p.close(); c.drawPath(p, fill=1, stroke=0)


def build_doc(path: Path, story, title: str, cover):
    doc = BaseDocTemplate(str(path), pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=22 * mm, bottomMargin=16 * mm, title=title, author=S["name"],
                          subject=S["assignment"])

    def cover_page(c, d):
        cover(c)

    def body_page(c, d):
        c.saveState()
        c.setFillColor(FOREST); c.rect(0, A4[1] - 14 * mm, A4[0], 14 * mm, fill=1, stroke=0)
        mark(c, 14 * mm, A4[1] - 12 * mm, 9 * mm)
        c.setFillColor(colors.white); c.setFont("Helvetica-Bold", 10.5); c.drawString(26 * mm, A4[1] - 8.2 * mm, "CaneSense AI")
        c.setFont("Helvetica", 7); c.setFillColor(LIME); c.drawString(26 * mm, A4[1] - 11.6 * mm, "PRECISION IRRIGATION INTELLIGENCE")
        c.setFillColor(colors.white); c.setFont("Helvetica", 8); c.drawRightString(A4[0] - 14 * mm, A4[1] - 9 * mm, title)
        c.restoreState()

    fr = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="f")
    doc.addPageTemplates([PageTemplate(id="cover", frames=[Frame(0, 0, A4[0], A4[1], leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0)], onPage=cover_page),
                          PageTemplate(id="body", frames=[fr], onPage=body_page)])
    doc.build(story, canvasmaker=Numbered)


