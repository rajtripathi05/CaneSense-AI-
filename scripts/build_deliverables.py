def md_story(md: str):
    out = []
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("# "):
            out.append(Paragraph(inline(ln[2:]), H1))
        elif ln.startswith("## "):
            out.append(Paragraph(inline(ln[3:]), H2))
        elif ln.startswith("### "):
            out.append(Paragraph(inline(ln[4:]), H3))
        elif ln.strip() == "---":
            out.append(Spacer(1, 4))
        elif ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            n = max(len(r) for r in rows)
            rows = [r + [""] * (n - len(r)) for r in rows]
            out.append(tbl(rows, [174 * mm / n] * n))
            out.append(Spacer(1, 4))
            continue
        elif ln.strip() == ">":
            pass
        elif ln.startswith("> "):
            out.append(Paragraph(inline(ln[2:]), ParagraphStyle("q", parent=B, leftIndent=10, textColor=colors.HexColor("#1D5A41"), borderPadding=2)))
        elif re.match(r"\s*- \[[ x]\] ", ln):
            out.append(Paragraph(inline(re.sub(r"\s*- \[[ x]\] ", "", ln)), BUL, bulletText="☐"))
        elif re.match(r"\s*[-*] ", ln):
            out.append(Paragraph(inline(re.sub(r"\s*[-*] ", "", ln, 1)), BUL, bulletText="•"))
        elif re.match(r"\d+\. ", ln):
            out.append(Paragraph(inline(ln.split(". ", 1)[1]), BUL, bulletText=ln.split(".")[0] + "."))
        elif ln.startswith("```"):
            i += 1
            buf = []
            while i < len(lines) and not lines[i].startswith("```"):
                buf.append(lines[i]); i += 1
            out.append(Preformatted("\n".join(buf), CODE))
        elif ln.strip():
            out.append(P(ln))
        i += 1
    return out


