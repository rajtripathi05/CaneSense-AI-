ax.set_xlim(0, 13); ax.set_ylim(0, 6.6); ax.axis("off")
G, L, W, GR = "#14432F", "#B7E36A", "#FFFFFF", "#66736C"


def box(x, y, w, h, text, fc=W, ec=G, tc="#1F2A26", fs=8.5, bold=False):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.08", fc=fc, ec=ec, lw=1.2))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs, color=tc, fontweight="bold" if bold else "normal")


def arrow(x1, y1, x2, y2):
    ax.annotate("", (x2, y2), (x1, y1), arrowprops=dict(arrowstyle="-|>", color=G, lw=1.3))


ax.add_patch(FancyBboxPatch((0.2, 0.2), 12.6, 6.2, boxstyle="round,pad=0.02,rounding_size=0.1", fc="#F5F3EA", ec="#E2DFD0"))
ax.text(0.45, 6.1, "CaneSense AI - system architecture (synthetic-data demo)", fontsize=12, fontweight="bold", color=G)
